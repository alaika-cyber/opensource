import { describe, it, expect } from "vitest";
import { db } from "../lib/db";
import { hashPassword, createSessionToken, verifySessionToken } from "../lib/auth";
import {
  calculateCommissions,
  validateAllocationRules,
  generateAgreementChecksum,
} from "../lib/commission";
import { recordLedgerEntry, processOrderRefund, getUserPayableBalance } from "../lib/ledger";
import { resolveAttribution, generateReferralCode } from "../lib/attribution";
import { Role, ProductType, CommissionModel, LedgerEntryType, OrderStatus } from "@prisma/client";

describe("OpenSource End-to-End User Journeys", () => {
  const timestamp = Date.now();
  let ownerId: string;
  let professionalId: string;
  let adminId: string;
  let productId: string;
  let teamId: string;
  let agreementId: string;
  let referralCode: string;
  let referralLinkId: string;
  let orderId: string;

  it("Journey 1: Owner and Professional Registration with secure auth", async () => {
    const passwordHash = await hashPassword("SecurePass2026!");

    const owner = await db.user.create({
      data: {
        email: `owner_${timestamp}@e2e.test`,
        passwordHash,
        name: "E2E Product Owner",
        role: Role.USER,
        emailVerified: true,
      },
    });
    ownerId = owner.id;
    expect(owner.id).toBeDefined();

    const professional = await db.user.create({
      data: {
        email: `pro_${timestamp}@e2e.test`,
        passwordHash,
        name: "E2E Growth Strategist",
        role: Role.USER,
        emailVerified: true,
        profile: {
          create: {
            headline: "Senior B2B Closer",
            skills: ["Outbound B2B", "Deal Negotiation"],
          },
        },
      },
    });
    professionalId = professional.id;
    expect(professional.id).toBeDefined();

    // Verify session tokens
    const token = await createSessionToken({
      userId: professional.id,
      email: professional.email,
      role: professional.role,
      name: professional.name,
    });
    const session = await verifySessionToken(token);
    expect(session?.userId).toBe(professional.id);
  });

  it("Journey 2: Product Owner publishes a product with commercial terms", async () => {
    const product = await db.product.create({
      data: {
        ownerId,
        name: `E2E Metrics Engine ${timestamp}`,
        slug: `e2e-metrics-engine-${timestamp}`,
        shortDesc: "Real-time metrics engine for microservices.",
        description: "Comprehensive telemetry aggregator and anomaly detection.",
        category: "Developer Tools",
        priceCents: 20000, // $200.00
        currency: "USD",
        commissionModel: CommissionModel.TEAM_POOL,
        commissionRateBps: 2000, // 20.00% pool
        attributionWindowDays: 60,
        status: "ACTIVE",
      },
    });
    productId = product.id;
    expect(product.priceCents).toBe(20000);
    expect(product.commissionRateBps).toBe(2000);
  });

  it("Journey 3: Growth team is created and members accept internal allocation splits", async () => {
    const team = await db.team.create({
      data: {
        name: `E2E Growth Syndicate ${timestamp}`,
        slug: `e2e-growth-syndicate-${timestamp}`,
        description: "Specialized team scaling developer tooling.",
        leaderId: professionalId,
        status: "ACTIVE",
      },
    });
    teamId = team.id;

    // Allocate 100% (10,000 bps) to the professional
    const member = await db.teamMember.create({
      data: {
        teamId: team.id,
        userId: professionalId,
        role: "LEADER",
        allocationBps: 10000,
        status: "ACTIVE",
      },
    });
    expect(member.allocationBps).toBe(10000);
  });

  it("Journey 4: Commercial agreement created and signed with SHA-256 checksum", async () => {
    const allocationRules = [
      { userId: professionalId, memberRole: "LEADER", allocationBps: 10000 },
    ];
    const termsText = "Owner grants 20% commission pool for verified sales generated by team.";

    const checksum = generateAgreementChecksum({
      productId,
      teamId,
      agreementVersion: 1,
      commissionModel: "TEAM_POOL",
      commissionPoolBps: 2000,
      allocationRulesJson: allocationRules,
      termsText,
    });

    const agreement = await db.commercialAgreement.create({
      data: {
        productId,
        teamId,
        agreementVersion: 1,
        commissionModel: CommissionModel.TEAM_POOL,
        commissionPoolBps: 2000,
        allocationRulesJson: allocationRules,
        termsText,
        checksum,
        status: "ACTIVE",
      },
    });
    agreementId = agreement.id;

    // Both parties sign
    await db.agreementAcceptance.createMany({
      data: [
        { agreementId, userId: ownerId, checksum },
        { agreementId, userId: professionalId, checksum },
      ],
    });

    const acceptances = await db.agreementAcceptance.findMany({ where: { agreementId } });
    expect(acceptances).toHaveLength(2);
  });

  it("Journey 5: Referral link generated and attributed to campaign", async () => {
    referralCode = generateReferralCode("E2E");
    const link = await db.referralLink.create({
      data: {
        productId,
        userId: professionalId,
        teamId,
        code: referralCode,
        targetUrl: `http://localhost:3000/products/e2e?ref=${referralCode}`,
      },
    });
    referralLinkId = link.id;
    expect(link.code).toBe(referralCode);
  });

  it("Journey 6: Attributed purchase recorded, integer commissions calculated, and ledger credited", async () => {
    // Verified $200.00 purchase (20,000 cents)
    const grossAmountCents = 20000;
    const orderNumber = `ORD-E2E-${timestamp}`;

    const order = await db.order.create({
      data: {
        orderNumber,
        productId,
        referralLinkId,
        customerEmail: "buyer@enterprise.com",
        grossAmountCents,
        currency: "USD",
        status: OrderStatus.COMPLETED,
        externalProviderRef: `pi_test_${timestamp}`,
        attributionRecord: {
          create: {
            method: "LAST_TOUCH_LINK",
            referralCode,
          },
        },
      },
    });
    orderId = order.id;

    // Calculate commissions: 20% pool = $40.00 (4,000 cents)
    // 5% platform fee = $2.00 (200 cents)
    // Net commission = $38.00 (3,800 cents)
    const calculation = calculateCommissions({
      grossSaleCents: grossAmountCents,
      commissionPoolBps: 2000,
      memberAllocations: [
        { userId: professionalId, memberRole: "LEADER", allocationBps: 10000 },
      ],
      platformFeeBps: 500,
    });

    expect(calculation.totalCommissionPoolCents).toBe(4000);
    expect(calculation.totalPlatformFeeCents).toBe(200);
    expect(calculation.totalNetCommissionCents).toBe(3800);

    const commEntry = await db.commissionEntry.create({
      data: {
        orderId: order.id,
        agreementId,
        userId: professionalId,
        teamId,
        calculationBasisCents: grossAmountCents,
        rateBps: 2000,
        memberShareBps: 10000,
        grossCommissionCents: 4000,
        platformFeeCents: 200,
        netCommissionCents: 3800,
        currency: "USD",
        status: "CONFIRMED",
        eligiblePayoutDate: new Date(),
      },
    });

    // Post to ledger
    await recordLedgerEntry({
      entryType: LedgerEntryType.COMMISSION_EARNED,
      referenceId: commEntry.id,
      userId: professionalId,
      commissionEntryId: commEntry.id,
      amountCents: 3800,
      idempotencyKey: `comm_order_${order.id}_user_${professionalId}`,
      description: `E2E Commission for Order #${order.orderNumber}`,
    });

    const balance = await getUserPayableBalance(professionalId);
    expect(balance).toBe(3800); // 3,800 cents = $38.00
  });

  it("Journey 7: Customer refund triggers auditable ledger reversal and cancels commissions", async () => {
    const refundResult = await processOrderRefund(orderId, "Customer cancellation request");
    expect(refundResult.order.status).toBe("REFUNDED");
    expect(refundResult.reversalResults).toHaveLength(1);

    // Balance should be reverted back to 0
    const balanceAfterRefund = await getUserPayableBalance(professionalId);
    expect(balanceAfterRefund).toBe(0);
  });
});
